import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import vue from '@vitejs/plugin-vue'
import { defineConfig } from 'vite'
import dts from 'vite-plugin-dts'
import { renderThemeCss } from './src/theme'

const src = fileURLToPath(new URL('./src', import.meta.url))

// Emit the design-token stylesheet so `violet-ui/style.css` works on its own
// (light + dark + prefers-color-scheme fallback, no JS needed).
writeFileSync(
  `${src}/styles/tokens.css`,
  `/* generated by vite.config.ts — do not edit */\n${renderThemeCss()}`,
)

// Library build: ESM only, one output module per source module for tree shaking.
export default defineConfig({
  plugins: [
    vue(),
    dts({
      tsconfigPath: './tsconfig.build.json',
      entryRoot: 'src',
      exclude: ['**/*.spec.ts', '**/*.stories.ts'],
    }),
  ],
  build: {
    target: 'es2022',
    cssCodeSplit: false,
    lib: {
      entry: { index: `${src}/index.ts`, resolver: `${src}/resolver.ts` },
      formats: ['es'],
      cssFileName: 'style',
    },
    rollupOptions: {
      external: ['vue'],
      output: { preserveModules: true, preserveModulesRoot: src, entryFileNames: '[name].js' },
    },
  },
})
